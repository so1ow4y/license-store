-- Отказ ХРАНИЛИЩА как отдельный исход журнала выдач.
--
-- До этого значения все отказы хранилища либо терялись из журнала, либо
-- смешивались бы с ERROR_CORRUPT. «Байты разошлись с эталоном» и «хранилище
-- недоступно» — разные инциденты с разными действиями, и различать их надо
-- в тот момент, когда идёт расследование, а не задним числом по логам.
ALTER TYPE "PayloadIssueResult" ADD VALUE IF NOT EXISTS 'ERROR_STORAGE';
