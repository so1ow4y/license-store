-- Запасной путь активации: по номеру заказа Digiseller.
--
-- Уникальные коды на карточке товара включены не всегда (unique_code_state
-- приходит null), и тогда покупателю предъявлять нечего, кроме номера заказа.
-- Уникального кода у такой сделки НЕ существует, поэтому колонка становится
-- NULL-able: в Postgres NULL не конфликтует с NULL, частичного индекса не
-- нужно, и обычный UNIQUE(unique_code) продолжает защищать путь с кодом.
--
-- Защиту от двойной выдачи по таким сделкам целиком несёт UNIQUE(inv_id),
-- который уже существует и проставляется обоими путями активации.
ALTER TABLE "digiseller_orders" ALTER COLUMN "unique_code" DROP NOT NULL;
