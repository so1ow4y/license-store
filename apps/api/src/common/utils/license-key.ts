/**
 * Ключ лицензии: маска для показа человеку и цензор для логов.
 *
 * Полный ключ — предъявительский документ: кто его видит, тот им и владеет
 * (привязки к аккаунту у ключа нет). Поэтому наружу по умолчанию уходит маска,
 * а полное значение — только по явному запросу владельца через отдельную ручку
 * с записью в аудит (§7 ТЗ бота).
 *
 * Файл лежит в common/utils, а не в модуле, потому что его импортируют три
 * независимых потребителя: экраны бота, сборщик payload'ов уведомлений и
 * сериализатор логгера. Копия в каждом из них разошлась бы с остальными при
 * первой же правке формата ключа — и разошлась бы молча.
 *
 * ВНИМАНИЕ, ОДНОИМЁННЫЙ ФАЙЛ: `@modules/launcher/dto/license-key.ts` экспортирует
 * СВОЮ константу `LICENSE_KEY_RE` — якорную (`^...$`), для ValidationPipe.
 * Здесь она намеренно названа иначе. Два разных регэкспа под одним именем в
 * двух файлах — это импорт не из того пути, который проходит типизацию,
 * компилируется и тихо меняет поведение: якорная регулярка в цензоре логов
 * не находит ключ в середине строки НИКОГДА, то есть цензура просто исчезает.
 */

/**
 * Хвост ключа: ровно четыре группы по четыре символа.
 *
 * Набор символов групп здесь ШИРЕ фактического алфавита генератора
 * (ACDEFGHJKMNPQRTUVWXYZ2346789, licenses.service.ts): для цензора ошибка
 * в сторону лишнего срабатывания стоит одну испорченную строку лога, а ошибка
 * в другую сторону — утёкший ключ. Сузить алфавит здесь значит перестать
 * ловить ключи, выданные до любого будущего изменения генератора.
 */
const KEY_TAIL = '(?:-[A-Z0-9]{4}){4}';

/**
 * Префикс — слаг продукта в верхнем регистре, и он МОЖЕТ СОДЕРЖАТЬ ДЕФИСЫ:
 * ключ собирается как `${productSlug.toUpperCase()}-${четыре группы}`, а слаг
 * продукта — это /^[a-z0-9][a-z0-9-]{1,62}[a-z0-9]$/ (products.dto.ts).
 *
 * Поэтому НЕ `[A-Z0-9]{2,6}`: такой префикс описывает только сегодняшние слаги
 * из сида (fc26, fc27, gta5), то есть совпадение, а не проверку. Первый же
 * продукт со слагом `gta-5` даёт ключи `GTA-5-ACDE-FGHJ-KMNP-QRTU`, которые
 * узкая регулярка не опознаёт — и такие ключи уезжали бы в логи открытыми,
 * причём именно у нового продукта, где утечка дороже всего.
 *
 * Верхняя граница 62 повторяет длину слага и заодно держит стоимость поиска
 * ограниченной: хвост фиксированной длины, вложенных неограниченных
 * квантификаторов нет, поэтому катастрофического отката (ReDoS) не возникает.
 */
const KEY_PREFIX = '[A-Z0-9][A-Z0-9-]{0,62}';

/**
 * Регулярка для ЗАМЕНЫ в тексте (флаг `g`).
 *
 * ИСПОЛЬЗОВАТЬ ТОЛЬКО В `String.prototype.replace`. Регулярка с флагом `g`
 * хранит `lastIndex` между вызовами, поэтому у `.test()` на ней результат
 * чередуется true/false на одной и той же строке. Для проверки есть
 * `containsLicenseKey`, для замены — `redactLicenseKeys`.
 *
 * Регистр только верхний: ключи генерируются в верхнем регистре и в таком же
 * виде лежат в БД, а `IsLicenseKey` приводит пользовательский ввод к верхнему
 * до валидации. Флаг `i` добавил бы ложные срабатывания на обычном тексте,
 * ничего не поймав дополнительно.
 */
export const LICENSE_KEY_SCAN_RE = new RegExp(`\\b${KEY_PREFIX}${KEY_TAIL}\\b`, 'g');

/** Та же регулярка без `g` — чтобы у проверки не было состояния. */
const LICENSE_KEY_TEST_RE = new RegExp(`\\b${KEY_PREFIX}${KEY_TAIL}\\b`);

/**
 * Есть ли в строке что-то похожее на ключ лицензии.
 *
 * Нужна в двух местах: цензор логов и проверка ввода в боте перед отправкой
 * кода в Digiseller. Во втором случае «похоже на ключ» означает «не отправлять»:
 * иначе ключ лицензии уедет в чужой сервис как неудачная попытка активации
 * и осядет в ИХ логах, откуда его уже не отозвать.
 */
export function containsLicenseKey(value: string): boolean {
  return LICENSE_KEY_TEST_RE.test(value);
}

/** Вырезает все ключи из произвольного текста. Точка вызова — сериализатор логгера. */
export function redactLicenseKeys(value: string): string {
  return value.replace(LICENSE_KEY_SCAN_RE, '***');
}

/**
 * Маска ключа для показа: `FC26-****-****-****-QRTU`.
 *
 * Открытыми остаются слаг продукта (он и так публичен — есть в каталоге)
 * и последняя группа: этого хватает, чтобы владелец узнал свою лицензию
 * в списке из пяти, и не хватает, чтобы ключом воспользоваться.
 *
 * Строки неизвестного формата маскируются ЦЕЛИКОМ. Попытка «умно» разобрать
 * формат, который мы не выдавали, — это способ однажды показать три четверти
 * чужого секрета: функцию зовут в том числе на значениях из payload'ов
 * уведомлений, где лежит не обязательно ключ.
 */
export function maskLicenseKey(key: string | null | undefined): string {
  if (!key) return '';

  const value = key.trim();
  // Границу проверяем ДО разбора: у 11-символьной строки первые четыре
  // и последние четыре символа перекрываются, и маска показала бы почти всё.
  if (value.length < 12) return '****';

  const parts = value.split('-');
  // Пять сегментов и больше — кандидат на наш формат: слаг (сам может быть
  // с дефисами) плюс ровно четыре группы. Слаг склеиваем обратно, а не берём
  // первые четыре символа: у ключа GTA-5-ACDE-... срез дал бы обрубок «GTA-».
  if (parts.length >= 5) {
    const groups = parts.slice(-4);
    // Четыре группы ОБЯЗАНЫ быть ровно по четыре символа. Без этой проверки
    // под формат подходит любой uuid (8-4-4-4-12), и функция отдавала бы
    // его наполовину открытым — при том, что в шапке обещано обратное.
    const groupsLookRight = groups.every((group) => /^[A-Z0-9]{4}$/i.test(group));
    const tail = groups[groups.length - 1];
    const prefix = parts.slice(0, parts.length - 4).join('-');

    if (groupsLookRight && prefix.length > 0 && tail !== undefined) {
      return `${prefix}-****-****-****-${tail}`;
    }
  }

  return '****';
}
