import { ApiProperty } from '@nestjs/swagger';
import { IsEmail, IsString, Matches, MaxLength } from 'class-validator';

/**
 * Код покупки Digiseller — ровно 16 символов (документация площадки).
 *
 * Проверка формата стоит здесь, а не только в сервисе, по практической
 * причине: она отсекает опечатки и перебор ДО обращения к площадке.
 * Единственный платёжный канал не должен тратить свои запросы на строки,
 * которые заведомо не являются кодом.
 */
export class RedeemCodeDto {
  @ApiProperty({ example: 'A1B2C3D4E5F6G7H8', description: '16 латинских букв и цифр' })
  @IsString()
  @Matches(/^[A-Za-z0-9]{16}$/, { message: 'Код покупки состоит из 16 латинских букв и цифр' })
  code!: string;
}

/**
 * Запасной путь активации: номер заказа Digiseller плюс почта покупателя.
 *
 * Оба поля обязательны, и второе — не удобство, а защита. Номер заказа
 * площадка выдаёт ПОДРЯД, он не секрет, и сам по себе он доказывает не
 * больше, чем номер дома. Единственное, что связывает предъявителя с
 * покупкой, — совпадение почты с buyer_info у площадки.
 *
 * Глобальный ValidationPipe включён с whitelist + forbidNonWhitelisted
 * (main.ts), поэтому третьего поля в теле быть не может: лишнее — это 400,
 * а не молчаливое отбрасывание. Здесь так и надо — набор проверяемых
 * реквизитов не должен зависеть от того, что прислал клиент.
 */
export class RedeemOrderDto {
  @ApiProperty({ example: '298114896', description: 'Номер заказа из письма площадки о покупке' })
  @IsString()
  @Matches(/^[0-9]{6,12}$/, { message: 'Номер заказа — от 6 до 12 цифр без пробелов' })
  orderNumber!: string;

  @ApiProperty({ example: 'buyer@example.com', description: 'Почта, на которую оформлялась покупка на площадке' })
  // Сравнение регистронезависимое и с обрезкой пробелов — это делает сервис.
  // Здесь только форма и длина: колонка почты в базе 255 символов, и всё,
  // что длиннее, — заведомо не адрес.
  @IsEmail({}, { message: 'Укажите почту, на которую оформлялась покупка' })
  @MaxLength(255)
  email!: string;
}
