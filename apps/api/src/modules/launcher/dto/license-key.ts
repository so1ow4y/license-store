import { Transform } from 'class-transformer';
import { IsString, Matches, MaxLength } from 'class-validator';

/**
 * Ключ лицензии в теле запроса загрузчика.
 *
 * ПОЧЕМУ В ТЕЛЕ, А НЕ В ЗАГОЛОВКЕ И НЕ В QUERY.
 *
 * Подпись запроса покрывает `METHOD \n path \n timestamp \n nonce \n
 * sha256(rawBody)` — то есть сырое тело целиком и НИ ОДНОГО заголовка, кроме
 * четырёх подписных, и НИ ОДНОГО параметра query (SignatureGuard.pathOf режет
 * строку по '?'). Ключ в теле оказывается внутри HMAC: посредник не может
 * подменить его, оставив подпись валидной, и переигранное тело нельзя
 * перенацелить на другую лицензию. Ключ в X-License-Key был бы единственным
 * параметром авторизации ВНЕ подписанного канона — в системе, которая прямо
 * признаёт рабочим сценарий с подставленным корневым сертификатом, это не
 * мелочь.
 *
 * Query дисквалифицирован дважды: параметр вне HMAC и он же в логах. nginx
 * пишет в access-лог $request_uri целиком, pino — req.url, AllExceptionsFilter
 * — строку `METHOD url → status`. Ключ уехал бы в хранилище логов, доступ
 * к которому шире доступа к БД.
 *
 * ИМЯ ПОЛЯ ОБЯЗАНО ОСТАВАТЬСЯ РОВНО `licenseKey`: от него уже зависят два
 * списка редактирования — pino redact.paths (`req.body.licenseKey`) и
 * REDACTED_FIELDS аудита. Переименование поля молча снимает цензуру.
 */

/**
 * Формат ключа: SLUG-XXXX-XXXX-XXXX-XXXX.
 *
 * Алфавит групп — ровно тот, которым ключ генерируется (licenses.service.ts,
 * KEY_ALPHABET): без B, I, L, O, S, 0, 1, 5, чтобы человек не путал их при
 * переносе руками. Регулярка здесь не косметика, а ПЕРВЫЙ и самый дешёвый
 * рубеж: мусорный перебор отбивается ValidationPipe'ом, не доходя ни до
 * Redis, ни до Postgres.
 *
 * Префикс — слаг продукта в верхнем регистре, поэтому у него свой,
 * более широкий набор символов.
 *
 * ПРЕФИКС ОБЯЗАН ПОВТОРЯТЬ SLUG_RE ИЗ products.dto.ts, ВКЛЮЧАЯ ДЕФИСЫ.
 * Прежняя запись `[A-Z0-9]{2,16}` дефис не допускала и обрывала префикс на
 * шестнадцати символах, тогда как слаг продукта — это
 * /^[a-z0-9][a-z0-9-]{1,62}[a-z0-9]$/, а ключ собирается как
 * `${productSlug.toUpperCase()}-${четыре группы}` (licenses.service.ts,
 * generateLicenseKey). Первый же продукт со слагом вида `gta-5` выдавал бы
 * ключи `GTA-5-ACDE-FGHJ-KMNP-QRTU`, которые ValidationPipe отбивает ДО
 * всякой логики — и не кодом LICENSE_KEY_INVALID, а голым 400, в проде
 * ещё и без текста (main.ts, disableErrorMessages при NODE_ENV=production).
 * Ни один покупатель такого продукта не запустился бы никогда, и причину
 * по ответу сервера было бы не установить. Сегодня спасают только слаги
 * из сида (fc26, fc27, gta5) — то есть совпадение, а не проверка.
 *
 * Верхняя граница длины здесь намеренно не считается: её держит MaxLength(64)
 * ниже, и держит по тому же основанию, что и колонка licenses.key —
 * VarChar(64).
 */
export const LICENSE_KEY_RE =
  /^[A-Z0-9][A-Z0-9-]{0,62}[A-Z0-9](?:-[ACDEFGHJKMNPQRTUVWXYZ2346789]{4}){4}$/;

/**
 * Общий набор ограничений для поля licenseKey.
 *
 * Собран одним декоратором намеренно: поле объявляется в трёх DTO, и
 * разъехавшиеся между ними регулярка или нормализация означали бы, что один
 * эндпоинт принимает ключ, который другой отвергает, — при том, что ключ
 * один и тот же.
 *
 * @Transform выполняется ДО валидации (ValidationPipe с transform: true),
 * поэтому регулярка проверяет уже канонизированное значение и ключ,
 * скопированный в нижнем регистре, проходит. На подпись это не влияет:
 * она посчитана по сырым байтам тела ещё в guard'е.
 */
export const IsLicenseKey = (): PropertyDecorator => {
  const applied: PropertyDecorator[] = [
    Transform(({ value }: { value: unknown }) =>
      typeof value === 'string' ? value.trim().replace(/\s+/g, '').toUpperCase() : value,
    ),
    IsString(),
    // MaxLength стоит ДО Matches и дублирует её потолок сознательно: колонка
    // licenses.key объявлена VarChar(64), и мегабайтная строка не должна
    // доходить до регулярки вовсе.
    MaxLength(64),
    Matches(LICENSE_KEY_RE, {
      message: 'licenseKey: формат SLUG-XXXX-XXXX-XXXX-XXXX',
    }),
  ];

  return (target, propertyKey) => {
    for (const decorate of applied) decorate(target, propertyKey);
  };
};
