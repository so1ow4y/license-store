import { ApiProperty } from '@nestjs/swagger';
import { IsNotEmpty, IsString, Matches, MaxLength } from 'class-validator';

import { IsLicenseKey } from './license-key';

/**
 * Тело запроса за payload'ом (TZ-LAUNCHER §7).
 *
 * Ровно четыре поля. clientVersion сюда НЕ входит: версия клиента приезжает
 * обязательным заголовком X-Client-Version (§2.1), и добавлять её четвёртым
 * полем значило бы завести второй источник одного и того же факта — плюс
 * сломать подпись на клиенте, которая считается по байтам тела.
 *
 * Глобальный ValidationPipe включён с whitelist + forbidNonWhitelisted
 * (main.ts), поэтому лишнее поле в теле — это 400, а не молчаливое
 * отбрасывание. Для эндпоинта, где тело подписано, так и надо: расхождение
 * между тем, что подписал клиент, и тем, что разобрал сервер, должно быть
 * видно сразу.
 */
export class PayloadRequestDto {
  /**
   * Регулярка, а не просто MaxLength, по двум причинам сразу.
   *
   * Первая: productSlug уезжает ВТОРЫМ ПОЛЕМ В AAD (crypto.buildPayloadBinding),
   * а поля AAD разделены одним 0x0A. Символ перевода строки внутри значения
   * подделал бы границу поля — и это единственное поле AAD, которое приходит
   * напрямую от клиента.
   *
   * Вторая: slug ищется findUnique'ом, то есть совпадение точное, и любой
   * символ вне этого набора всё равно даст 404 — но уже после запроса в БД.
   */
  @ApiProperty({ example: 'fc26' })
  @IsString()
  @Matches(/^[a-z0-9][a-z0-9._-]{0,63}$/, {
    message: 'productSlug: строчные латинские буквы, цифры, . _ -',
  })
  productSlug!: string;

  @ApiProperty({
    description: 'Нормализованный Disk ID: без пробелов, в верхнем регистре',
    example: 'WD-WCC4N1234567',
  })
  @IsString()
  @IsNotEmpty()
  @MaxLength(128)
  hwid!: string;

  /**
   * 32 случайных байта в hex НИЖНЕГО регистра, свежие на каждый запрос (§7.2.1).
   *
   * Единственный гейт на 400: ниже по стеку CryptoService.derivePayloadKey
   * на неверном значении бросает 500, потому что туда оно может попасть
   * только при обойдённой валидации — то есть это уже наша ошибка, а не
   * клиентская.
   *
   * Верхний регистр не принимаем и не нормализуем. Два допустимых
   * представления одного ключа однажды разъедутся в векторах и тестах:
   * на этом проекте расхождение регистра уже один раз стоило транспортного
   * слоя (docs/SIGNATURE-VECTORS.md отстал от §3.5 ревизии 2).
   */
  @ApiProperty({
    description: '32 случайных байта в hex нижнего регистра, новые на каждый запрос',
    example: '3f2a…',
  })
  @IsString()
  @Matches(/^[0-9a-f]{64}$/, {
    message: 'sessionKey: ровно 64 символа hex нижнего регистра',
  })
  sessionKey!: string;

  /**
   * Ключ предъявляется В КАЖДОМ запросе, а не обменивается один раз
   * на короткоживущий тикет из license/check.
   *
   * Вариант с тикетом отвергнут (PAYLOAD-DESIGN §8, вариант «б»): он ломает
   * главное свойство этого эндпоинта — лицензия и HWID проверяются НА КАЖДЫЙ
   * запрос, а не «кто-то пять минут назад прошёл проверку». С тикетом
   * LICENSE_BLOCKED, выставленный между двумя запросами, не сработал бы,
   * а окно отзыва перестало бы быть одной управляемой величиной
   * (recheckAfterSec). Экономии тикет тоже не даёт: findUnique по UNIQUE-
   * индексу key дешевле прежнего выбора лицензии по (userId, productId).
   */
  @ApiProperty({ example: 'FC26-3HJ4-XUND-ETAZ-9877' })
  @IsLicenseKey()
  licenseKey!: string;
}
