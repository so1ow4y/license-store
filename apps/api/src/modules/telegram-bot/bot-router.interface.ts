import type { TgUpdate } from './dto/telegram-update.types';

/**
 * Шов между транспортом и логикой бота.
 *
 * ЗАЧЕМ ТОКЕН, А НЕ ПРЯМОЙ ИМПОРТ КЛАССА. Обработчик очереди
 * (TelegramUpdateProcessor) — транспорт: он умеет доставать апдейт,
 * сериализовать чат и погасить исключение. Что означает апдейт, он не
 * знает и знать не должен. Прямой импорт BotRouterService затянул бы
 * в транспорт весь граф экранов, лицензий и биллинга, и модуль
 * TelegramApiModule, который импортирует NotificationsModule, перестал
 * бы быть лёгким.
 *
 * Реализацию к токену привязывает сборка модуля:
 *   { provide: BOT_ROUTER, useExisting: BotRouterService }
 */
export const BOT_ROUTER = Symbol('BOT_ROUTER');

export interface BotRouter {
  /**
   * Обработать один апдейт.
   *
   * Вызывается уже под блокировкой чата — внутри можно считать, что
   * параллельного апдейта из того же чата сейчас нет.
   *
   * Исключение отсюда гасится и логируется обработчиком: Telegram уже
   * получил 200, повторять апдейт некому, и падение одного экрана не
   * должно останавливать разбор очереди.
   */
  handleUpdate(update: TgUpdate): Promise<void>;

  /**
   * Удалить из чатов сообщения с полными ключами, которым вышел срок.
   *
   * Отдельная операция, а не часть handleUpdate, потому что она НЕ привязана
   * к приходу апдейта: человек мог раскрыть ключ и больше в бота не вернуться,
   * а сообщение с рабочим ключом обязано исчезнуть из переписки в любом
   * случае. Зовётся обработчиком очереди по расписанию.
   *
   * Не бросает: уборка не имеет права остановить разбор очереди.
   */
  sweepExpiredKeyMessages(): Promise<void>;
}
