/**
 * Экранирование для parse_mode: 'HTML'.
 *
 * ЗАЧЕМ. Telegram разбирает разметку в тексте сообщения. Любая подстановка
 * пользовательских данных — @username, название продукта, текст обращения —
 * это чужой ввод в разметку. Незакрытый «<» роняет отправку целиком
 * («can't parse entities»), а закрытый превращает часть сообщения бота
 * в чужую ссылку: экран «ваша лицензия активна» с чужим href на фишинг
 * выглядит убедительнее любого письма.
 *
 * Отсюда правило пакета 3: КАЖДОЕ значение переменной проходит через
 * escapeHtml перед подстановкой в шаблон, а не «то, что выглядит опасным».
 *
 * Набор символов взят из документации Bot API: для HTML-разметки Telegram
 * требует заменять «<», «>» и «&». Кавычка добавлена сверх: она встречается
 * внутри href="…" у кнопок-ссылок, и без неё атрибут закрывается досрочно.
 */
export function escapeHtml(value: unknown): string {
  if (value === null || value === undefined) return '';

  return String(value)
    // Амперсанд ПЕРВЫМ: иначе следующая замена превратит уже вставленный
    // &lt; в &amp;lt; и пользователь увидит сущность вместо символа.
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/**
 * Обрезка длинного значения.
 *
 * Применяется к СЫРОМУ значению, до escapeHtml. Наоборот нельзя: обрезка
 * уже экранированной строки способна разрубить сущность пополам («&am»),
 * и Telegram отвергнет сообщение целиком.
 *
 * Нужна не для красоты: лимит текста сообщения — 4096 символов, и один
 * длинный ввод пользователя (название, текст обращения) уносит с собой
 * весь экран, а не только себя.
 */
export function truncate(value: string, max: number): string {
  if (max <= 0) return '';
  if (value.length <= max) return value;
  // Многоточие занимает один символ и обязано поместиться в лимит,
  // иначе «обрезка» возвращает строку длиннее запрошенной.
  return `${value.slice(0, max - 1).trimEnd()}…`;
}
