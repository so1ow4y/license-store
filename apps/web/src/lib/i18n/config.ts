/**
 * Языки интерфейса и их неизменяемые свойства.
 *
 * Отдельный файл без импортов намеренно: его тянут и хранилище языка, и
 * словарь ошибок, и нижний слой запросов. Любая зависимость отсюда на React
 * или на api превратилась бы в цикл импорта.
 */

/**
 * Порядок важен: он же порядок кнопок в переключателе.
 * Первый элемент — язык по умолчанию.
 */
export const LOCALES = ['en', 'ru'] as const

export type Locale = (typeof LOCALES)[number]

/**
 * Английский — язык по умолчанию. Не «русский, потому что сервер русский»:
 * машинные коды сервера языка не имеют, а тексты принадлежат фронту.
 */
export const DEFAULT_LOCALE: Locale = 'en'

/**
 * Название языка ВСЕГДА на нём самом.
 *
 * Человек, попавший на незнакомый ему язык интерфейса, ищет глазами знакомые
 * буквы. Написать «Russian» в английском интерфейсе значит спрятать выход
 * ровно от того, кому он нужен.
 */
export const LOCALE_NAMES: Record<Locale, string> = {
  en: 'English',
  ru: 'Русский',
}

/** Двухбуквенная подпись для компактного переключателя. */
export const LOCALE_SHORT: Record<Locale, string> = {
  en: 'EN',
  ru: 'RU',
}

/**
 * Значение заголовка `Accept-Language`.
 *
 * Русский идёт с английским в хвосте: если у сервера когда-нибудь не окажется
 * русского шаблона письма, он должен взять английский, а не молча промолчать.
 */
export const ACCEPT_LANGUAGE: Record<Locale, string> = {
  en: 'en',
  ru: 'ru, en;q=0.8',
}

export function isLocale(value: unknown): value is Locale {
  return typeof value === 'string' && (LOCALES as readonly string[]).includes(value)
}
