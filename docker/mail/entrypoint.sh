#!/usr/bin/env bash
# ============================================================================
#  Запуск postfix в одной из двух ролей.
#
#    MAIL_ROLE=out — внутренний отправитель (портов наружу нет)
#    MAIL_ROLE=mx  — публичный приёмник (порты 25 и 587)
#
#  ЧТО ЭТОТ СКРИПТ ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ.
#
#  Не делает: не генерирует main.cf. Конфигурация целиком лежит в
#  docker/mail/conf/<роль>/ и копируется как есть. Именно из-за генерации мы
#  и ушли от чужого образа: файл, которого никто не видел целиком, невозможно
#  сопровождать.
#
#  Делает: подставляет то немногое, что ОБЯЗАНО отличаться между окружениями
#  (домен, адрес пересылки, подсети, пути к сертификатам, пароль submission),
#  и строит индексы таблиц. Каждая подстановка помечена в конфигурации
#  комментарием [entrypoint], чтобы по файлу было видно, что перекрывается.
# ============================================================================

set -euo pipefail

log() { echo "[mail-entrypoint] $*"; }
die() { echo "[mail-entrypoint] ОШИБКА: $*" >&2; exit 1; }

ROLE="${MAIL_ROLE:-}"
DOMAIN="${MAIL_DOMAIN:-pxcheats.com}"

case "$ROLE" in
    out|mx) ;;
    *) die "MAIL_ROLE должен быть 'out' или 'mx', получено: '${ROLE}'" ;;
esac

# --- 1. Конфигурация роли ---------------------------------------------------

SRC="/etc/postfix-role/$ROLE"
[ -f "$SRC/main.cf" ]   || die "нет $SRC/main.cf — образ собран неправильно"
[ -f "$SRC/master.cf" ] || die "нет $SRC/master.cf — образ собран неправильно"

install -m 0644 "$SRC/main.cf"   /etc/postfix/main.cf
install -m 0644 "$SRC/master.cf" /etc/postfix/master.cf
log "роль $ROLE: конфигурация установлена"

# --- 2. Значения, зависящие от окружения ------------------------------------

postconf -e "mydomain=$DOMAIN"
postconf -e "myorigin=\$mydomain"

if [ "$ROLE" = "out" ]; then
    # Имя в HELO. По умолчанию — сам домен: ровно то, что видел Gmail, когда
    # принимал наши письма с первой попытки. Менять только вместе с живой
    # проверкой доставки.
    postconf -e "myhostname=${MAIL_HOSTNAME:-$DOMAIN}"
    # Кому разрешено сдавать нам письма. См. развёрнутое объяснение в
    # conf/out/main.cf — коротко: у контейнера нет опубликованных портов,
    # поэтому широкий диапазон docker здесь ничего не открывает.
    postconf -e "mynetworks=${MAIL_INTERNAL_NETWORKS:-127.0.0.0/8 172.16.0.0/12}"
    # От кого разрешено отправлять. В файле роли стоит домен по умолчанию —
    # здесь он приводится к реальному MAIL_DOMAIN.
    #
    # ЧТО К ПРОБЛЕМЕ ВЕЛО: без smtpd_sender_restrictions любой, кто оказался
    # в сети compose (а туда входит и шлюз docker-сети на хосте), мог сдать
    # нам письмо от ЛЮБОГО отправителя любому получателю в мире — и мы
    # доставили бы его своим IP и своей репутацией.
    #
    # Запятых внутри {} быть не должно: список ограничений разбирается по
    # запятым раньше, чем inline-таблица.
    postconf -e "smtpd_sender_restrictions=reject_non_fqdn_sender, check_sender_access inline:{$DOMAIN=OK}, reject"
    # Проверка сразу, на месте: молча не совпавший домен здесь означает 554
    # на каждое письмо платформы.
    if [ "$(postmap -q "$DOMAIN" "inline:{$DOMAIN=OK}" 2>/dev/null || true)" != "OK" ]; then
        die "inline-таблица отправителей не отвечает для домена $DOMAIN — postfix этой версии не понимает inline:{}"
    fi
    log "разрешённый отправитель: любой адрес @$DOMAIN, остальное 554"
else
    # Приёмник представляется тем именем, по которому его нашли, — то есть
    # значением записи MX.
    postconf -e "myhostname=${MAIL_MX_HOSTNAME:-mail.$DOMAIN}"
    postconf -e "virtual_alias_domains=$DOMAIN"
    postconf -e "smtpd_sasl_local_domain=$DOMAIN"
fi

# --- 3. Таблицы -------------------------------------------------------------

# ПУСТАЯ КАРТА ЛОКАЛЬНЫХ ПОЛУЧАТЕЛЕЙ. Нужна ОБЕИМ ролям.
#
# ЧТО К ПРОБЛЕМЕ ВЕЛО: в обоих main.cf стояло `local_recipient_maps =`, и
# читалось это как «локальных получателей нет». У postfix пустое значение
# означает обратное — «не проверять, принимать всех». А в локальный класс
# адресов при inet_interfaces = all входят адреса интерфейсов в квадратных
# скобках, поэтому `RCPT TO:<foo@[127.0.0.1]>` принимался кодом 250, попадал
# в очередь, уходил в local(8) — и возвращался ОТЛУПОМ с телом письма на
# адрес отправителя, подставленный кем угодно.
#
# Существующая, но пустая карта означает «не находится никто»: отказ 550 на
# RCPT TO, ни байта очереди, ни одного отлупа.
cat > /etc/postfix/local_recipients <<'EOF'
# ПУСТО НАМЕРЕННО, И ПУСТОТА ЗДЕСЬ ЗНАЧИМА.
#
# Файл собирается при старте (docker/mail/entrypoint.sh) и существует ради
# того, чтобы local_recipient_maps была НЕПУСТОЙ как параметр и пустой как
# содержимое. Пустой параметр у postfix означает «принимать всех локальных
# получателей», непустая карта без записей — «не принимать никого».
#
# Добавить сюда адрес — значит завести локальный ящик, которого в этой
# системе нет и не должно быть: почта принимается только через
# virtual_alias_maps и только пересылается.
EOF
postmap /etc/postfix/local_recipients
log "локальных получателей нет ни одного (карта пуста)"

# Дальше — только для роли mx: отправителю принимать нечего, и лишние карты
# у него были бы просто способом однажды принять то, что принимать не
# собирались.

if [ "$ROLE" = "mx" ]; then
    FORWARD_TO="${MAIL_FORWARD_TO:-}"
    [ -n "$FORWARD_TO" ] || die "MAIL_FORWARD_TO не задан — некуда пересылать почту с $DOMAIN"

    # sed по плейсхолдерам, а не envsubst: envsubst разворачивает ЛЮБОЕ
    # $ИМЯ в файле, включая случайные доллары в комментариях, и молча
    # заменяет неизвестные на пустоту.
    sed -e "s|%MAIL_DOMAIN%|$DOMAIN|g" \
        -e "s|%MAIL_FORWARD_TO%|$FORWARD_TO|g" \
        /etc/postfix-role/virtual.template > /etc/postfix/virtual
    postmap /etc/postfix/virtual

    sed -e "s|%MAIL_DOMAIN%|$DOMAIN|g" \
        /etc/postfix-role/sender_login.template > /etc/postfix/sender_login
    postmap /etc/postfix/sender_login

    # Переписывание КОНВЕРТА пересылаемых писем (sender_canonical в main.cf).
    #
    # ЧТО К ПРОБЛЕМЕ ВЕЛО: без него отлуп от Gmail на письмо, которое мы
    # приняли и не смогли доставить, уходил на адрес отправителя из конверта
    # — а он у спам-ботов подделан. Это backscatter с нашего IP, проходящий
    # наш же SPF, и прямая дорога в чёрные списки.
    #
    # Точки в домене обезвреживаются: в таблице regexp: точка без экранирования
    # означает «любой символ», и шаблон совпадал бы, например, с «pxcheatsXcom».
    # Ошибка безобидная, но она из тех, что живут годами.
    #
    # Каждая точка заменяется на класс [.], а НЕ на \. — намеренно.
    # Обратная косая здесь прошла бы через три интерпретатора (bash → sed →
    # postfix), и в каждом её надо удваивать; такие строки ломаются при первой
    # же правке, причём МОЛЧА: шаблон остаётся рабочим, просто перестаёт быть
    # точным. У [.] нет ни одного спецсимвола, и он значит ровно то же.
    DOMAIN_RE=$(printf '%s' "$DOMAIN" | sed 's/[.]/[.]/g')
    sed -e "s|%MAIL_DOMAIN_RE%|$DOMAIN_RE|g" \
        -e "s|%MAIL_DOMAIN%|$DOMAIN|g" \
        /etc/postfix-role/sender_canonical.template > /etc/postfix/sender_canonical
    # postmap здесь НЕ нужен и вреден: regexp-таблицы читаются как текст, а
    # postmap создал бы рядом .db, который никто не открывает, — и правка
    # файла выглядела бы применённой, не будучи применённой.
    #
    # Проверка сразу: чужой отправитель обязан переписаться, наш — остаться.
    probe_foreign=$(postmap -q 'probe@example.org' regexp:/etc/postfix/sender_canonical || true)
    probe_own=$(postmap -q "postmaster@$DOMAIN" regexp:/etc/postfix/sender_canonical || true)
    [ "$probe_foreign" = "forward@$DOMAIN" ] \
        || die "sender_canonical не переписывает чужой адрес (получено: '${probe_foreign:-<пусто>}') — отлупы уйдут подделанным отправителям"
    [ "$probe_own" = "postmaster@$DOMAIN" ] \
        || die "sender_canonical переписывает НАШ адрес (получено: '${probe_own:-<пусто>}') — проверь шаблон"
    log "переписывание конверта: чужой отправитель → forward@$DOMAIN, свой — без изменений"

    # Показать итог в журнале: при разборе «почему письмо не дошло» первый
    # вопрос — какие адреса вообще существуют.
    log "принимаемые адреса:"
    grep -vE '^\s*(#|$)' /etc/postfix/virtual | sed 's/^/  /'
fi

# --- 4. TLS -----------------------------------------------------------------
#
# Сертификат берётся тот же, что у nginx: каталог смонтирован только для
# чтения. Отдельный сертификат для почты — это отдельное продление, которое
# однажды забудут; общий продлевается тем же certbot, что и сайт.
#
# ПОЧЕМУ КОПИРУЕМ, А НЕ ЧИТАЕМ НА МЕСТЕ. Закрытый ключ приезжает от certbot
# с правами 600 root, а smtpd после старта сбрасывает привилегии до
# пользователя postfix и прочитать его не может. Копия root:postfix 0640
# решает это, не трогая исходный файл и не ослабляя права на него.
CERT_SRC="/etc/postfix/certs"
if [ -s "$CERT_SRC/fullchain.pem" ] && [ -s "$CERT_SRC/privkey.pem" ]; then
    install -o root -g postfix -m 0644 "$CERT_SRC/fullchain.pem" /etc/postfix/tls/fullchain.pem
    install -o root -g postfix -m 0640 "$CERT_SRC/privkey.pem"   /etc/postfix/tls/privkey.pem
    chgrp postfix /etc/postfix/tls
    postconf -e "smtpd_tls_cert_file=/etc/postfix/tls/fullchain.pem"
    postconf -e "smtpd_tls_key_file=/etc/postfix/tls/privkey.pem"
    # У роли «out» уровень в файле стоит none — поднимаем, раз сертификат
    # есть: так поведение остаётся тем же, что и у прежнего образа, который
    # STARTTLS предлагал. У роли «mx» уровень уже `may` и трогать его нечем.
    postconf -e "smtpd_tls_security_level=may"
    log "TLS: сертификат подключён"
else
    # Не die: приёмник без TLS работает (STARTTLS просто не предлагается), а
    # отправитель тем более — трафик от API не покидает хост. Ронять почту
    # из-за отсутствия сертификата было бы хуже проблемы.
    postconf -e "smtpd_tls_security_level=none"
    postconf -e "smtpd_tls_auth_only=no"
    log "TLS: сертификата нет ($CERT_SRC), STARTTLS выключен"
    if [ "$ROLE" = "mx" ]; then
        log "  ВНИМАНИЕ: submission на 587 без сертификата работать не будет —"
        log "  там TLS обязателен. Для приёма на 25 это не помеха."
    fi
fi

# --- 5. Учётная запись submission -------------------------------------------
#
# Заводится при каждом старте заново: база sasldb2 живёт внутри контейнера и
# исчезает вместе с ним. Так пароль существует ровно в одном месте — в
# .env.production на сервере, — и не может «остаться старым» в томе, о
# котором все забыли.
if [ "$ROLE" = "mx" ] && [ -n "${MAIL_SUBMISSION_PASSWORD:-}" ]; then
    SUB_USER="${MAIL_SUBMISSION_USER:-support}"
    rm -f /etc/postfix/sasl/sasldb2
    # -p читает пароль со стандартного ввода без запроса терминала: терминала
    # в контейнере нет, и без -p команда падает на чтении.
    printf '%s' "$MAIL_SUBMISSION_PASSWORD" \
        | saslpasswd2 -p -c -f /etc/postfix/sasl/sasldb2 -u "$DOMAIN" "$SUB_USER"
    chown root:postfix /etc/postfix/sasl/sasldb2
    chmod 0640 /etc/postfix/sasl/sasldb2
    log "submission: заведена учётка ${SUB_USER}@${DOMAIN}"
elif [ "$ROLE" = "mx" ]; then
    # Без пароля служба submission остаётся объявленной, но войти в неё
    # нельзя ничем — а значит, и отправить через неё нельзя ничего.
    log "submission: пароль не задан (MAIL_SUBMISSION_PASSWORD), вход невозможен"
fi

# --- 6. Проверка и запуск ---------------------------------------------------

# Создаёт недостающие каталоги очереди и ругается на неверные права. Дешевле
# узнать об этом здесь, чем по молчаливо неработающей доставке.
#
# НЕ фатально (|| true при set -e): postfix check возвращает ненулевой код и
# на замечаниях, которые доставке не мешают, — например, на правах каталога,
# принесённых томом с хоста. Настоящую ошибку конфигурации всё равно поймает
# сам postfix ниже: он отказывается стартовать с нечитаемым main.cf или
# неизвестной директивой. Ронять почту на предупреждении нельзя.
postfix check || log "postfix check с замечаниями (см. выше) — продолжаем"

log "postconf -n:"
postconf -n | sed 's/^/  /'

# start-fg держит процесс на переднем плане и корректно обрабатывает SIGTERM,
# то есть `docker stop` даёт postfix закрыть очередь, а не убивает его.
exec postfix start-fg
