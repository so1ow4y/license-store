#!/bin/bash
# ============================================================================
#  Проба живости почтового контейнера. Обе роли, out и mx.
#
#  ЧТО К ПРОБЛЕМЕ ВЕЛО. Здесь стояло `postfix status`, а комментарий рядом
#  утверждал, что «postfix отвечает на своём же порту». Комментарий описывал
#  проверку, которой не было: `postfix status` спрашивает только, жив ли
#  процесс master. А master остаётся жив, когда его дети падают — он их для
#  того и перезапускает.
#
#  Именно так это и сломалось. postscreen падал при каждом запуске
#  («invalid postscreen_pre_queue_limit value 8 < 10»), master послушно
#  поднимал его снова, `postfix status` отвечал «is running», docker считал
#  контейнер healthy, deploy.sh печатал зелёное «почтовый сервер проверен» —
#  а приём почты не работал вовсе. Соединение на порт 25 при этом
#  устанавливалось: его принимает docker-proxy, который не знает и не может
#  знать, есть ли кто-нибудь за портом.
#
#  Отсюда правило: проба обязана разговаривать по протоколу, а не спрашивать
#  у системы её мнение о себе.
#
#  ПОЧЕМУ ЭТО БЫСТРО, ХОТЯ У mx ЕСТЬ postscreen. postscreen задерживает
#  баннер на postscreen_greet_wait (6 с), чтобы поймать клиентов, которые
#  начинают говорить раньше времени. Но в main.cf роли mx стоит
#  postscreen_access_list = permit_mynetworks при mynetworks = 127.0.0.0/8, а
#  проба идёт изнутри контейнера с 127.0.0.1 — то есть в обход всех проверок
#  postscreen, сразу к smtpd. Баннер приходит немедленно, кэш postscreen не
#  засоряется, в журнале не появляется записи на каждые 30 секунд.
#
#  Права релея это не даёт: доступ к smtpd и право пересылки решаются разными
#  параметрами, и в smtpd_relay_restrictions у роли mx permit_mynetworks нет.
#
#  127.0.0.1, а не localhost: имя резолвится в ::1 первым, а postfix внутри
#  контейнера слушает IPv4.
# ============================================================================
set -u

exec 3<>/dev/tcp/127.0.0.1/25 || {
    echo "порт 25 не принимает соединение"
    exit 1
}

IFS= read -r -t 4 -u 3 line || {
    echo "соединение есть, баннера нет — за портом никого"
    exec 3<&-; exec 3>&-
    exit 1
}

# Вежливо прощаемся: брошенное соединение оставляет smtpd висеть до таймаута
# и занимает один из восьми процессов. Раз в 30 секунд это заметно.
printf 'QUIT\r\n' >&3 2>/dev/null
exec 3<&-; exec 3>&-

case "$line" in
    220*) exit 0 ;;
    # 421 отдают при перегрузке или остановке — это не «здоров».
    *)    echo "баннер не 220: $line"; exit 1 ;;
esac
