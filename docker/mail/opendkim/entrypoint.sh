#!/usr/bin/env bash
# ============================================================================
#  Запуск подписанта DKIM.
#
#  Порядок важен: сначала приёмник syslog (иначе первые строки опендkim'а,
#  включая жалобы на ключ, пропадут бесследно), потом рабочая копия ключа,
#  потом список «своих» сетей, и только затем сам демон — на переднем плане
#  и первым процессом, чтобы docker видел его смерть.
# ============================================================================

set -euo pipefail

log() { echo "[opendkim-entrypoint] $*"; }
die() { echo "[opendkim-entrypoint] ОШИБКА: $*" >&2; exit 1; }

DOMAIN="${MAIL_DOMAIN:-pxcheats.com}"
# Имя переменной с приставкой MAIL_ намеренно НЕ совпадает с DKIM_SELECTOR из
# .env.production. DKIM_SELECTOR там — переключатель подписи в nodemailer, и
# он обязан оставаться пустым: два подписанта на одном селекторе поставят на
# письмо две подписи, из которых проверится одна. Совпадение имён рано или
# поздно привело бы к «да это же одно и то же, давай заполним».
SELECTOR="${MAIL_DKIM_SELECTOR:-mail}"
KEY_SRC="${DKIM_KEY_FILE:-/etc/opendkim/keys/dkim.private}"
KEY_DST="/var/lib/opendkim/keys/dkim.private"

# --- 1. Журнал --------------------------------------------------------------
#
# opendkim умеет писать ТОЛЬКО в syslog. busybox syslogd поднимает /dev/log и
# перекладывает всё в stdout, то есть в `docker logs lp-opendkim`.
# Запускается в фоне: если он однажды умрёт, подпись продолжит работать —
# потеря журнала хуже, чем ничего, но несравнимо лучше остановки почты.
mkdir -p /var/run/opendkim
chown opendkim:opendkim /var/run/opendkim
busybox syslogd -n -O /dev/stdout &
log "приёмник syslog поднят"

# --- 2. Ключ ----------------------------------------------------------------
#
# ПОЧЕМУ КОПИЯ, А НЕ ЧТЕНИЕ НА МЕСТЕ. Ключ приезжает с хоста как root:root
# 0600 (так его кладёт deploy.sh), а демон работает от пользователя opendkim
# и прочитать его не может. Прежний образ решал это командой chown ПРЯМО НА
# СМОНТИРОВАННОМ ФАЙЛЕ — из-за чего том нельзя было подключить только для
# чтения: на :ro chown падает, и контейнер уходил в вечный перезапуск с
# одной строкой «Read-only file system».
#
# Копия снимает это ограничение: исходный файл монтируется :ro и остаётся
# нетронутым, а права на копию ровно те, которых требует RequireSafeKeys.
[ -s "$KEY_SRC" ] || die "нет закрытого ключа DKIM: $KEY_SRC"
grep -q 'PRIVATE KEY' "$KEY_SRC" || die "$KEY_SRC не похож на ключ PEM"

install -o opendkim -g opendkim -m 0400 "$KEY_SRC" "$KEY_DST"
log "ключ на месте: $KEY_DST (селектор $SELECTOR, домен $DOMAIN)"

# --- 3. Кого считаем «своим» ------------------------------------------------
#
# Только эти адреса получают ПОДПИСЬ; всё остальное opendkim лишь проверяет.
# Значение по умолчанию совпадает с mynetworks роли «out» — это один и тот же
# набор: сеть compose, из которой приходит API.
INTERNAL="${MAIL_INTERNAL_NETWORKS:-127.0.0.0/8 172.16.0.0/12}"
{
    echo "# Собран при старте из MAIL_INTERNAL_NETWORKS. Править здесь бесполезно:"
    echo "# файл перезаписывается при каждом запуске контейнера."
    for net in $INTERNAL; do
        # Квадратные скобки — синтаксис postfix для IPv6; opendkim их не
        # понимает и молча пропустит строку целиком, поэтому снимаем.
        echo "${net//[\[\]]/}"
    done
} > /var/lib/opendkim/InternalHosts
chown opendkim:opendkim /var/lib/opendkim/InternalHosts
chmod 0444 /var/lib/opendkim/InternalHosts
log "InternalHosts: $INTERNAL"

# --- 4. Домен и селектор ----------------------------------------------------
#
# Ровно две строки конфигурации зависят от окружения. Всё остальное — файл
# в репозитории, который применяется как есть.
#
# Якорь ^Domain[[:space:]] обязателен: без него sed попал бы и в SubDomains.
sed -i -E \
    -e "s|^Domain[[:space:]].*|Domain                  ${DOMAIN}|" \
    -e "s|^Selector[[:space:]].*|Selector                ${SELECTOR}|" \
    /etc/opendkim/opendkim.conf

# --- 5. Запуск --------------------------------------------------------------
#
# -f — не уходить в фон, -x — файл настроек. Первым процессом контейнера,
# чтобы docker перезапускал контейнер при падении демона.
log "запуск opendkim"
exec opendkim -f -x /etc/opendkim/opendkim.conf
