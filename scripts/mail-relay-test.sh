#!/usr/bin/env bash
# ============================================================================
#  Проверка приёмника почты на открытый релей. Запускается НА СЕРВЕРЕ:
#
#      cd /opt/license-platform && bash scripts/mail-relay-test.sh
#
#  ЗАЧЕМ ОТДЕЛЬНО ОТ mail-check.sh. Тот проверяет, что почта работает; этот —
#  что она не работает для чужих. Разные вопросы, и второй надо задать РАНЬШЕ:
#  открытый релей находят сканеры за часы, а из чёрных списков выходят
#  неделями — вместе с отправкой всей платформы, то есть с регистрацией и
#  выдачей лицензий.
#
#  ПОЧЕМУ ЗАПУСК С САМОГО СЕРВЕРА ЗДЕСЬ ПРАВИЛЬНЫЙ, ХОТЯ ОБЫЧНО НЕТ.
#  Обычное возражение: с сервера соединение приходит с адреса, который может
#  попасть в mynetworks, и вы проверите permit_mynetworks вместо защиты.
#  Здесь оно не действует, и вот почему — это проверено в самом файле, а не
#  предполагается (см. «Раздел 0» ниже, он сверяет это на живом postfix):
#
#    * у роли mx  mynetworks = 127.0.0.0/8, и mynetworks_style = host;
#    * в smtpd_relay_restrictions у неё НЕТ permit_mynetworks вовсе —
#      только permit_sasl_authenticated, reject_unauth_destination.
#
#  Сверх того, при публикации порта postfix видит адресом источника шлюз сети
#  docker (172.x), а не 127.0.0.1. То есть проверка идёт с ЧАСТНОГО адреса —
#  ровно из того диапазона, который в чужих настройках чаще всего и получает
#  право релея. Отказ такому клиенту означает отказ и публичному; обратного
#  случая не бывает.
#
#  ЗАЧЕМ ЗДЕСЬ ЕСТЬ ПОЛОЖИТЕЛЬНАЯ ПРОВЕРКА (раздел 2). Набор проверок, где всё
#  обязано быть отвергнуто, целиком проходит на сервере, который просто лежит:
#  «соединение отклонено» тоже не релей. Поэтому один адрес обязан быть
#  ПРИНЯТ. Без него зелёный вывод этого скрипта не значит ничего.
# ============================================================================
set -uo pipefail

HOST="${1:-127.0.0.1}"
PORT="${2:-25}"
TIMEOUT="${SMTP_TIMEOUT:-10}"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DOMAIN="$(grep -E '^MAIL_DOMAIN=' "$ROOT/.env.production" 2>/dev/null | cut -d= -f2- | tr -d '[:space:]')"
DOMAIN="${DOMAIN:-pxcheats.com}"

# Отправитель для проб. НЕ example.org и НЕ example.com: у обоих в DNS стоит
# nullMX (запись MX с пустой целью, RFC 7505) — «этот домен почту не
# принимает». Postfix проверяет домен отправителя ДО получателя и отвечает
# «550 Sender address rejected ... (nullMX)», не дойдя до правил пересылки.
#
# Проверка на этом не падает — она молча превращается в проверку чего-то
# другого: все пробы отвергнуты, вывод зелёный, а про релей не выяснено
# ничего. Ровно это здесь и случилось при первом запуске.
#
# Поэтому домен отправителя обязан быть настоящим и чужим. Письмо всё равно не
# отправляется: до DATA проба не доходит никогда, разговор обрывается на RCPT.
PROBE_FROM="${PROBE_FROM:-probe@gmail.com}"
# Чужой получатель для проб на пересылку — тоже настоящий домен, но другой.
PROBE_TO="${PROBE_TO:-probe@yahoo.com}"

FAILED=0
log()  { echo -e "\n\033[36m=== $* ===\033[0m"; }
ok()   { echo -e "  \033[32m[ok]\033[0m $*"; }
bad()  { echo -e "  \033[31m[ДЫРА]\033[0m $*"; FAILED=$((FAILED + 1)); }
warn() { echo -e "  \033[33m[?]\033[0m $*"; }

# --- Разговор по SMTP на голом bash -----------------------------------------
#
# swaks на сервере нет, а ставить пакет ради проверки, которая делается
# двадцатью строками, — лишняя зависимость в проде. /dev/tcp есть в bash
# всегда, и его наличие уже проверено на шаге 0 плана.
REPLY_ALL=""
EHLO_ALL=""
_read_reply() {
    local line last=""
    REPLY_ALL=""
    while IFS= read -r -t "$TIMEOUT" -u 3 line; do
        line="${line%$'\r'}"
        last="$line"
        REPLY_ALL+="$line"$'\n'
        # Последняя строка ответа — та, где после кода пробел, а не дефис.
        [[ "$line" =~ ^[0-9]{3}\  ]] && break
        [[ "$line" =~ ^[0-9]{3}$ ]] && break
    done
    printf '%s' "$last"
}
_send() { printf '%s\r\n' "$1" >&3; }

# Одна проба: подключиться, представиться, назвать отправителя и получателя,
# вернуть ответ ИМЕННО НА RCPT TO. Дальше DATA не идём никогда — принятое
# письмо пришлось бы вынимать из очереди руками.
#
# Печатает: "<код> <текст>" либо "CONN <причина>", если соединения нет.
smtp_probe() {
    local from="$1" rcpt="$2" reply

    exec 3<>"/dev/tcp/$HOST/$PORT" 2>/dev/null || { printf 'CONN отказано'; return; }

    reply="$(_read_reply)"                                  # баннер 220
    [[ "$reply" =~ ^220 ]] || { exec 3<&-; exec 3>&-; printf 'CONN нет баннера: %s' "$reply"; return; }

    # БЕЗ подстановки команд: $( ) — это подоболочка, и REPLY_ALL, выставленный
    # внутри неё, до вызывающего не доходит. Список возможностей нужен целиком
    # (раздел 4), поэтому читаем в текущей оболочке, а вывод глушим.
    _send "EHLO relay-probe.invalid"; _read_reply >/dev/null; EHLO_ALL="$REPLY_ALL"
    _send "MAIL FROM:<$from>";        reply="$(_read_reply)"
    if [[ ! "$reply" =~ ^2 ]]; then
        # Отказ уже здесь — тоже отказ, дальше RCPT не будет. Возвращаем как есть,
        # пометив стадию: иначе «554 на MAIL FROM» прочитается как ответ на RCPT.
        _send "QUIT" 2>/dev/null; exec 3<&-; exec 3>&-
        printf 'MAILFROM %s' "$reply"; return
    fi
    _send "RCPT TO:<$rcpt>";          reply="$(_read_reply)"
    _send "QUIT" 2>/dev/null
    exec 3<&-; exec 3>&-
    printf '%s' "$reply"
}

# Ожидаем отказ: годится 5xx на любой стадии.
expect_reject() {
    local name="$1" from="$2" rcpt="$3" r
    r="$(smtp_probe "$from" "$rcpt")"
    case "$r" in
        CONN*)          warn "$name — соединения нет ($r). Проверка не состоялась." ;;
        MAILFROM\ 5*)   ok   "$name — отказ уже на MAIL FROM: ${r#MAILFROM }" ;;
        5*)             ok   "$name — отказ: $r" ;;
        4*)             warn "$name — временный отказ: $r. Это не дыра, но и не защита." ;;
        2*)             bad  "$name — ПРИНЯТО: $r" ;;
        *)              warn "$name — непонятный ответ: $r" ;;
    esac
}

expect_accept() {
    local name="$1" from="$2" rcpt="$3" r
    r="$(smtp_probe "$from" "$rcpt")"
    case "$r" in
        2*) ok  "$name — принято: $r" ;;
        *)  bad "$name — НЕ принято: $r
      Приёмник отвергает собственный адрес. Вся проверка выше ничего не
      доказывает: сервер, который отказывает всем, релеем тоже не является." ;;
    esac
}

echo "Приёмник: $HOST:$PORT, домен: $DOMAIN"

# --- 0. Сверить предпосылку, а не поверить в неё -----------------------------
log "0. На чём держится право этой проверки"
if docker exec lp-postfix-mx postconf -h smtpd_relay_restrictions >/dev/null 2>&1; then
    RR="$(docker exec lp-postfix-mx postconf -h smtpd_relay_restrictions 2>/dev/null | tr -d '\r')"
    MN="$(docker exec lp-postfix-mx postconf -h mynetworks 2>/dev/null | tr -d '\r')"
    echo "  smtpd_relay_restrictions = $RR"
    echo "  mynetworks               = $MN"
    if echo "$RR" | grep -q 'permit_mynetworks'; then
        bad "у приёмника ЕСТЬ permit_mynetworks — проверка с сервера здесь
      недействительна, потому что источником будет частный адрес шлюза docker.
      Либо убрать permit_mynetworks, либо проверять только с чужой машины."
    else
        ok "permit_mynetworks отсутствует — частный адрес источника прав не даёт"
    fi
else
    warn "контейнер lp-postfix-mx недоступен для postconf — предпосылка не сверена"
fi

# --- Разогрев: пройти postscreen --------------------------------------------
#
# У роли mx на порту 25 стоит postscreen. Первое соединение с незнакомого
# адреса он ОТКЛАДЫВАЕТ: молчит postscreen_greet_wait секунд, проверяя, не
# заговорит ли клиент раньше времени (так делают только рассыльщики), затем
# отвечает «450 4.3.2 Service currently unavailable» и запоминает адрес как
# приличный на postscreen_greet_ttl. Настоящий почтовый сервер после 450
# просто повторит попытку через несколько минут.
#
# Для проверки это значит: ПЕРВАЯ проба всегда получит 450 и не проверит
# ничего. Если этого не знать, «450» прочитается как защита от релея, а на
# деле до правил пересылки дело даже не дошло. Поэтому одно соединение
# тратим осознанно и в счёт не берём.
log "Разогрев: проходим postscreen"
_warm="$(smtp_probe "$PROBE_FROM" "$PROBE_TO")"
case "$_warm" in
    4*|MAILFROM\ 4*) ok "postscreen отложил первое соединение ($_warm) и запомнил адрес" ;;
    CONN*)           warn "разогрев не удался: $_warm" ;;
    *)               ok "postscreen пропустил сразу ($_warm)" ;;
esac

# --- 1. Релей: то, ради чего всё --------------------------------------------
log "1. Пересылка чужой почты чужому адресату"
expect_reject "классический релей"      "$PROBE_FROM"  "$PROBE_TO"
expect_reject "пустой отправитель"      ""             "$PROBE_TO"
expect_reject "процентный обход"        "$PROBE_FROM"  "probe%yahoo.com@$DOMAIN"
expect_reject "двойная собака"          "$PROBE_FROM"  "probe@yahoo.com@$DOMAIN"
expect_reject "маршрут через двоеточие" "$PROBE_FROM"  "@$DOMAIN:probe@yahoo.com"
expect_reject "восклицательный путь"    "$PROBE_FROM"  "yahoo.com!probe@$DOMAIN"
expect_reject "адрес-литерал"           "$PROBE_FROM"  "probe@[127.0.0.1]"
# Литерал с настоящим адресом сервера — отдельная проба: разбор адреса у
# postfix может считать «своим» именно его. Если адрес не определился, пробу
# пропускаем, а не подставляем пустые скобки: на них придёт 501 «синтаксис»,
# и он зачтётся как защита, которой на самом деле не проверяли.
MYIP="$(hostname -I 2>/dev/null | awk '{print $1}')"
if [ -n "$MYIP" ]; then
    expect_reject "литерал нашего адреса" "$PROBE_FROM" "probe@[$MYIP]"
else
    warn "адрес сервера не определился — проба с литералом своего адреса пропущена"
fi

# --- 2. Обратная сторона: свой адрес обязан приниматься ----------------------
log "2. Своя почта принимается (иначе проверка выше ничего не значит)"
expect_accept "support@$DOMAIN" "$PROBE_FROM" "support@$DOMAIN"

# --- 3. Несуществующий адрес: отказ на RCPT, а не отлуп ----------------------
#
# ЧЕМ ПЛОХ ОТЛУП. Приняв письмо и не сумев его доставить, postfix обязан
# сообщить отправителю — а отправитель в спаме подделан. Мы разошлём отлупы
# невиновным и попадём в Backscatterer, откуда выходят вместе с отправкой.
log "3. Несуществующий адрес отвергается сразу"
expect_reject "нет-такого@$DOMAIN" "$PROBE_FROM" "нет-такого-адреса@$DOMAIN"

# --- 4. Что приёмник о себе объявляет ---------------------------------------
log "4. Объявленные возможности"
smtp_probe "$PROBE_FROM" "support@$DOMAIN" >/dev/null
CAPS="$EHLO_ALL"
if [ -z "$CAPS" ]; then
    warn "список возможностей не получен"
else
    # DSN: NOTIFY=SUCCESS превращает приёмник в генератор писем по чужому заказу.
    if echo "$CAPS" | grep -qi '^250[ -]DSN'; then
        bad "объявлен DSN — можно заказать уведомление на любой адрес"
    else
        ok "DSN не объявлен"
    fi
    # AUTH на 25 без TLS — это раздача пароля в открытом виде всем, кто спросит.
    if echo "$CAPS" | grep -qi '^250[ -]AUTH'; then
        bad "на порту 25 объявлен AUTH — пароль уйдёт в открытом виде"
    else
        ok "AUTH на 25 не объявлен"
    fi
    echo "$CAPS" | grep -qi '^250[ -]STARTTLS' && ok "STARTTLS есть" || warn "STARTTLS не объявлен"
    echo "$CAPS" | sed 's/^/      /'
fi

# --- 5. VRFY и EXPN: выдача списка адресов ----------------------------------
log "5. VRFY / EXPN"
if exec 3<>"/dev/tcp/$HOST/$PORT" 2>/dev/null; then
    _read_reply >/dev/null
    _send "EHLO relay-probe.invalid"; _read_reply >/dev/null
    _send "VRFY support@$DOMAIN"; V="$(_read_reply)"
    _send "QUIT"; exec 3<&-; exec 3>&-
    case "$V" in
        5*) ok   "VRFY отключён: $V" ;;
        2*) bad  "VRFY отвечает подтверждением: $V — это перебор адресов" ;;
        *)  warn "VRFY: $V" ;;
    esac
else
    warn "соединение для VRFY не открылось"
fi

echo
if [ "$FAILED" -eq 0 ]; then
    echo -e "\033[32m=== Дыр не найдено. Приёмник можно открывать наружу ===\033[0m"
    echo "  MAIL_MX_BIND=0.0.0.0 в .env.production, затем выложить заново."
    echo "  После открытия ЭТУ ЖЕ проверку повторить с чужой машины:"
    echo "      bash scripts/mail-relay-test.sh mail.$DOMAIN 25"
    exit 0
fi
echo -e "\033[31m=== Найдено дыр: $FAILED. Наружу НЕ открывать ===\033[0m"
exit 1
